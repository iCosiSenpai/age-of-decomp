#!/usr/bin/env python3
"""Content guard: no game material, keys or build output may enter the repository.

  py tools/check_content.py --staged    files staged for commit (pre-commit hook)
  py tools/check_content.py --all       every tracked file (CI)

Fails on: dump/game extensions, key files, generated game C markers, files under ignored build folders, and binaries
larger than 4 MiB outside the allow-list (fonts, icons). Sizes and contents come from the index, the bytes a commit
takes, not from the working tree: a partly staged file is checked as it will be committed.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORBIDDEN_EXT = {".nup", ".nsp", ".nsz", ".xci", ".xcz", ".nca", ".ncz", ".nso", ".nro", ".npdm", ".keys", ".tik",
                 ".bfres", ".sarc", ".zs", ".bntx", ".bfsha", ".g1t", ".g1m", ".ktf2", ".ktsl2stbin", ".rdb", ".fdata"}
FORBIDDEN_NAMES = {"prod.keys", "title.keys", "dev.keys", "hwaoi.exe", "hwaoi"}
FORBIDDEN_DIRS = ("work/", ".cache/", "out/", "build/", "generated/", "refs/", "plan&activity/")
ALLOW_LARGE = {".ttf", ".png", ".ico", ".icns", ".svg"}
GENERATED_MARKERS = (b"Generated by recomp/gen.py", b"hwaoi196608-full")
HEAD_BYTES = 4096


def files(staged: bool) -> list[str]:
    cmd = ["git", "diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"] if staged else ["git", "ls-files", "-z"]
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, check=True).stdout.decode("utf-8")
    return [f for f in out.split("\0") if f]


def index_blobs() -> dict[str, str]:
    """Path -> blob id of every index entry (submodules, which hold a commit, are left out)."""
    out = subprocess.run(["git", "ls-files", "-s", "-z"], cwd=ROOT, capture_output=True, check=True).stdout
    blobs = {}
    for entry in out.decode("utf-8").split("\0"):
        if not entry:
            continue
        meta, name = entry.split("\t", 1)
        mode, blob, _stage = meta.split()
        if mode != "160000":
            blobs[name] = blob
    return blobs


class Blobs:
    """Size and first bytes of index blobs, read through one `git cat-file --batch` process."""

    def __init__(self) -> None:
        self.proc = subprocess.Popen(["git", "cat-file", "--batch"], cwd=ROOT, stdin=subprocess.PIPE,
                                     stdout=subprocess.PIPE)

    def read(self, blob: str) -> tuple[int, bytes]:
        assert self.proc.stdin is not None and self.proc.stdout is not None
        self.proc.stdin.write(blob.encode("ascii") + b"\n")
        self.proc.stdin.flush()
        header = self.proc.stdout.readline().split()
        if len(header) != 3 or header[1] != b"blob":
            raise RuntimeError(f"git cat-file answered {header!r} for {blob}")
        size = int(header[2])
        head = self.proc.stdout.read(min(size, HEAD_BYTES))
        rest = size - len(head)
        while rest > 0:  # skip the remainder without keeping it
            rest -= len(self.proc.stdout.read(min(rest, 1 << 20)))
        self.proc.stdout.read(1)  # the newline after the content
        return size, head

    def close(self) -> None:
        if self.proc.stdin is not None:
            self.proc.stdin.close()
        self.proc.wait()


def problems(name: str, blob: str | None, blobs: Blobs) -> list[str]:
    low = name.lower()
    suffix = Path(low).suffix
    found = []
    if suffix in FORBIDDEN_EXT:
        found.append("game/dump file type")
    if Path(low).name in FORBIDDEN_NAMES:
        found.append("key file or built game")
    if low.startswith(FORBIDDEN_DIRS) or "age of imprisonment switch 2 nup" in low:
        found.append("file inside an ignored build/dump folder")
    if blob:
        size, head = blobs.read(blob)
        if size > 4 << 20 and suffix not in ALLOW_LARGE:
            found.append(f"large file ({size >> 20} MiB)")
        if suffix in (".c", ".h") and any(m in head for m in GENERATED_MARKERS):
            found.append("generated game code")
    return found


def main() -> int:
    staged = "--staged" in sys.argv
    index, blobs = index_blobs(), Blobs()
    try:
        bad = [(f, pr) for f in files(staged) for pr in [problems(f, index.get(f), blobs)] if pr]
    finally:
        blobs.close()
    for f, pr in bad:
        print(f"{f}: {', '.join(pr)}")
    print(f"content check: {'FAILED' if bad else 'ok'} ({'staged' if staged else 'tracked'} files)")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
