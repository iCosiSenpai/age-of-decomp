#!/usr/bin/env python3
"""Content guard: no game material, keys or build output may enter the repository.

  py tools/check_content.py --staged    files staged for commit (pre-commit hook)
  py tools/check_content.py --all       every tracked file (CI)

Fails on: dump/game extensions, key files, generated game C markers, files under ignored build folders, and binaries
larger than 4 MiB outside the allow-list (fonts, icons).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORBIDDEN_EXT = {".nup", ".nsp", ".nsz", ".xci", ".xcz", ".nca", ".ncz", ".nso", ".nro", ".npdm", ".keys", ".tik",
                 ".bfres", ".sarc", ".zs", ".bntx", ".bfsha", ".g1t", ".g1m", ".ktsl2stbin", ".rdb", ".fdata"}
FORBIDDEN_NAMES = {"prod.keys", "title.keys", "dev.keys", "hwaoi.exe", "hwaoi"}
FORBIDDEN_DIRS = ("work/", ".cache/", "out/", "build/", "generated/", "refs/", "plan&activity/")
ALLOW_LARGE = {".ttf", ".png", ".ico", ".icns", ".svg"}
GENERATED_MARKERS = (b"Generated by recomp/gen.py", b"hwaoi196608-full")


def files(staged: bool) -> list[str]:
    cmd = ["git", "diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"] if staged else ["git", "ls-files", "-z"]
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, check=True).stdout.decode("utf-8")
    return [f for f in out.split("\0") if f]


def problems(name: str) -> list[str]:
    p = ROOT / name
    low = name.lower()
    found = []
    if Path(low).suffix in FORBIDDEN_EXT:
        found.append("game/dump file type")
    if Path(low).name in FORBIDDEN_NAMES:
        found.append("key file or built game")
    if low.startswith(FORBIDDEN_DIRS) or "age of imprisonment switch 2 nup" in low:
        found.append("file inside an ignored build/dump folder")
    if p.is_file():
        size = p.stat().st_size
        if size > 4 << 20 and p.suffix.lower() not in ALLOW_LARGE:
            found.append(f"large file ({size >> 20} MiB)")
        if p.suffix.lower() in (".c", ".h") and size > 0:
            head = p.read_bytes()[:4096]
            if any(m in head for m in GENERATED_MARKERS):
                found.append("generated game code")
    return found


def main() -> int:
    staged = "--staged" in sys.argv
    bad = [(f, pr) for f in files(staged) for pr in [problems(f)] if pr]
    for f, pr in bad:
        print(f"{f}: {', '.join(pr)}")
    print(f"content check: {'FAILED' if bad else 'ok'} ({'staged' if staged else 'tracked'} files)")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
